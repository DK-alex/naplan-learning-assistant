const dictionaries = {
  en: english,
  "zh-TW": traditional,
  ko: korean,
};

function interpolate(template, values = {}) {
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function translate(language, source, values) {
  const template = language === "zh-CN" ? source : dictionaries[language]?.[source] || source;
  return interpolate(template, values);
}

export function getLocale(language) {
  return locales[language] || locales[DEFAULT_UI_LANGUAGE];
}

export function getLanguageLabel(language) {
  return languageOptions.find((option) => option.value === language)?.label || languageOptions[0].label;
}

const I18nContext = createContext({
  language: DEFAULT_UI_LANGUAGE,
  locale: locales[DEFAULT_UI_LANGUAGE],
  t: (source, values) => interpolate(source, values),
});

export function I18nProvider({ language, children }) {
  const value = useMemo(
    () => ({
      language,
      locale: getLocale(language),
      t: (source, values) => translate(language, source, values),
    }),
    [language],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
