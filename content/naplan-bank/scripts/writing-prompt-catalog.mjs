function changeClause(item) {
  return item.change.replace(/^(?:when|after|as soon as)\s+/i, "");
}

function visualMetadata(year, genre, key, title, visual) {
  const assetId = `writing-y${year}-${genre}-${key}`;
  return {
    asset_id: assetId,
    src: `/assets/writing-prompts/year-${year}/${assetId}.webp`,
    alt_text: `Original illustrated writing stimulus for "${title}": ${visual}.`,
    generation_prompt: [
      `Create an original NAPLAN-style writing stimulus illustration for Year ${year}.`,
      `Topic: ${title}.`,
      `Scene: ${visual}.`,
      "Editorial children's-book illustration, landscape 4:3 composition, clear focal point, several open-ended story or argument cues, culturally inclusive Australian setting where appropriate.",
      "No words, letters, numbers, logos, watermarks, official branding, answer text or decorative border.",
      "The image must support multiple interpretations and must not prescribe one correct response.",
    ].join(" "),
    generated_by: "OpenAI image generation",
    generation_method: "built-in image_gen",
    status: "generated",
  };
}

function buildNarrative(year, item, index) {
  const yearIndex = YEAR_INDEX.get(year);
  const support = NARRATIVE_SUPPORT[year];
  const title = item.titles[yearIndex];
  return {
    catalog_id: `Y${year}-N-${String(index + 1).padStart(3, "0")}`,
    genre: "narrative",
    title,
    task: support.task(title),
    context: support.context(item),
    instructions: support.focus,
    idea_starters: support.starters(item),
    remember: REMEMBER,
    image: visualMetadata(year, "narrative", item.key, title, item.visual),
  };
}

function buildPersuasive(year, item, index) {
  const yearIndex = YEAR_INDEX.get(year);
  const support = PERSUASIVE_SUPPORT[year];
  const title = item.titles[yearIndex];
  const statement = item.statements[yearIndex];
  return {
    catalog_id: `Y${year}-P-${String(index + 1).padStart(3, "0")}`,
    genre: "persuasive",
    title,
    statement,
    task: support.task(statement),
    context: support.context(item),
    instructions: support.focus,
    idea_starters: support.starters(item),
    remember: REMEMBER,
    image: visualMetadata(year, "persuasive", item.key, title, item.visual),
  };
}

export function getWritingPromptCatalog(year) {
  if (!YEAR_INDEX.has(year)) throw new Error(`Unsupported writing prompt year: ${year}`);
  return [
    ...NARRATIVE_CONCEPTS.slice(0, 50).map((item, index) => buildNarrative(year, item, index)),
    ...PERSUASIVE_CONCEPTS.slice(0, 50).map((item, index) => buildPersuasive(year, item, index)),
  ];
}

